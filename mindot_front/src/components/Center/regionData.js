export const regionNames = Object.keys(regionData).sort((firstName, secondName) => (
  firstName.localeCompare(secondName, 'ko-KR')
))

// 시·군·구 이름을 가나다순으로 반환하는 처리.
export const getDistrictNames = (regionName) => (
  Object.keys(regionData[regionName] ?? {}).sort((firstName, secondName) => (
    firstName.localeCompare(secondName, 'ko-KR')
  ))
)

// 선택한 시·군·구에 포함된 읍·면·동 이름을 가나다순으로 반환하는 처리.
export const getTownNames = (regionName, districtName) => (
  [...(regionData[regionName]?.[districtName] ?? [])].sort((firstName, secondName) => (
    firstName.localeCompare(secondName, 'ko-KR')
  ))
)
